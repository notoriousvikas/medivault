import { TimelineEvent } from './timeline-event.model.js';
import { Record } from '../records/record.model.js';
import { Prescription } from '../prescriptions/prescription.model.js';
import { AppError, catchAsync } from '../../middleware/error.middleware.js';

const listTimelineEvents = catchAsync(async (req, res) => {
  const userId = req.user.userId;

  // 1. Fetch any explicit timeline events
  const manualEvents = await TimelineEvent.find({ userId }).lean();

  // 2. Fetch records and prescriptions to compile full chronological medical timeline
  const [records, prescriptions] = await Promise.all([
    Record.find({ userId }).sort({ uploadDate: -1 }).lean(),
    Prescription.find({ userId }).sort({ date: -1 }).lean(),
  ]);

  // Set of reference IDs already present in explicit timeline events to avoid duplication
  const existingRefIds = new Set(
    manualEvents
      .filter((e) => e.referenceId)
      .map((e) => e.referenceId.toString())
  );

  const synthesizedEvents = [];

  // Add health records to timeline
  for (const r of records) {
    if (!existingRefIds.has(r._id.toString())) {
      synthesizedEvents.push({
        _id: `rec-${r._id}`,
        userId,
        eventType: r.category || 'Record',
        category: r.category || 'Record',
        title: r.title,
        description:
          r.parsedData?.summary ||
          r.parsedData?.aiAnalysis ||
          `${r.category || 'Clinical document'} secured in AyuRaksha`,
        date: r.uploadDate || r.createdAt || new Date(),
        referenceId: r._id,
        relatedRecordId: r._id,
        isAutoGenerated: true,
      });
    }
  }

  // Add clinical prescriptions to timeline
  for (const p of prescriptions) {
    if (!existingRefIds.has(p._id.toString())) {
      const medsList = (p.medications || [])
        .map((m) => m.name)
        .filter(Boolean)
        .join(', ');

      synthesizedEvents.push({
        _id: `rx-${p._id}`,
        userId,
        eventType: 'Prescription',
        category: 'Prescription',
        title: `Prescription: Dr. ${p.doctorName}`,
        description: medsList ? `Medications: ${medsList}` : 'Pharmacy prescription order',
        date: p.date || p.createdAt || new Date(),
        referenceId: p._id,
        relatedRecordId: null,
        isAutoGenerated: true,
      });
    }
  }

  // Combine and sort chronologically descending (newest event first)
  const allEvents = [...manualEvents, ...synthesizedEvents].sort(
    (a, b) => new Date(b.date || b.createdAt || 0) - new Date(a.date || a.createdAt || 0)
  );

  res.status(200).json({
    status: 'success',
    results: allEvents.length,
    data: allEvents,
  });
});

const getTimelineEvent = catchAsync(async (req, res) => {
  const event = await TimelineEvent.findOne({
    _id: req.params.id,
    userId: req.user.userId,
  });

  if (!event) throw new AppError('Timeline event not found.', 404);

  res.status(200).json({ status: 'success', data: event });
});

const createTimelineEvent = catchAsync(async (req, res) => {
  const { eventType, title, date, referenceId } = req.body;

  if (!eventType || !title) {
    throw new AppError('Event type and title are required.', 400);
  }

  const event = await TimelineEvent.create({
    userId: req.user.userId,
    eventType,
    title,
    date: date || Date.now(),
    referenceId: referenceId || undefined,
  });

  res.status(201).json({ status: 'success', data: event });
});

const updateTimelineEvent = catchAsync(async (req, res) => {
  const { eventType, title, date, referenceId } = req.body;

  const updateFields = {};
  if (eventType !== undefined) updateFields.eventType = eventType;
  if (title !== undefined) updateFields.title = title;
  if (date !== undefined) updateFields.date = date;
  if (referenceId !== undefined) updateFields.referenceId = referenceId;

  const event = await TimelineEvent.findOneAndUpdate(
    { _id: req.params.id, userId: req.user.userId },
    updateFields,
    { new: true, runValidators: true }
  );

  if (!event) throw new AppError('Timeline event not found.', 404);

  res.status(200).json({ status: 'success', data: event });
});

const deleteTimelineEvent = catchAsync(async (req, res) => {
  const event = await TimelineEvent.findOneAndDelete({
    _id: req.params.id,
    userId: req.user.userId,
  });

  if (!event) throw new AppError('Timeline event not found.', 404);

  res.status(204).end();
});

export {
  listTimelineEvents,
  getTimelineEvent,
  createTimelineEvent,
  updateTimelineEvent,
  deleteTimelineEvent,
};
